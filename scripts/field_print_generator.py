def parse():
    res = [[0 for _ in range(len(prints))] for _ in range(8)]

    for i, sprite in enumerate(prints):
        rows = list(map(lambda x: x.strip() , sprite.split('\n')))[1:-1]

        for j, row in enumerate(reversed(rows)):
            print(f'{j}: {row}')
            for k, symb in enumerate(row):
                res[k][i] += (1 << j) * (symb == FILLED)


    for i in range(8):
        with open(f"../nums/row{i}.img", "w") as f:
            f.write('v2.0 raw\n')
            f.writelines(map(lambda b: f"{b:0x}\n", res[i]))

if __name__ == '__main__':
    parse()
        